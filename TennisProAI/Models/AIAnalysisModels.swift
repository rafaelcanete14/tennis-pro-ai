import Foundation
import SwiftData

// MARK: - Pose & Biomechanical Observation Payloads

struct NormalizedJointPoint: Codable, Equatable, Sendable {
    var jointName: String
    /// Normalized Vision coordinates (0...1, origin bottom-left in Vision; converted in overlay view).
    var x: Double
    var y: Double
    var confidence: Double
}

struct PoseBiomechanicsMetrics: Codable, Equatable, Sendable {
    var rightElbowAngleDegrees: Double?
    var leftElbowAngleDegrees: Double?
    var rightKneeAngleDegrees: Double?
    var leftKneeAngleDegrees: Double?
    var dominantWristAboveShoulder: Bool
    var estimatedCourtZone: String
    var joints: [NormalizedJointPoint]
}

// MARK: - Candidate Highlight Suggestion (Non-Fabricated Event Proposal)

struct CandidateHighlightEvent: Identifiable, Codable, Equatable, Sendable {
    var id: UUID
    var startTimestamp: Double
    var endTimestamp: Double
    var peakTimestamp: Double
    var detectionSource: String
    var observationSummary: String
    /// Confidence score ONLY present if emitted by a genuine Vision / CoreML observation.
    var modelConfidence: Double?
    var modelVersion: String
    /// Assigned manually by the user during review (or by a verified loaded CoreML shot classifier).
    var userSelectedCategory: HighlightCategory
    var isSelectedForExport: Bool

    init(
        id: UUID = UUID(),
        startTimestamp: Double,
        endTimestamp: Double,
        peakTimestamp: Double,
        detectionSource: String,
        observationSummary: String,
        modelConfidence: Double?,
        modelVersion: String,
        userSelectedCategory: HighlightCategory = .rally,
        isSelectedForExport: Bool = true
    ) {
        self.id = id
        self.startTimestamp = startTimestamp
        self.endTimestamp = endTimestamp
        self.peakTimestamp = peakTimestamp
        self.detectionSource = detectionSource
        self.observationSummary = observationSummary
        self.modelConfidence = modelConfidence
        self.modelVersion = modelVersion
        self.userSelectedCategory = userSelectedCategory
        self.isSelectedForExport = isSelectedForExport
    }
}

// MARK: - SwiftData AIAnalysisRecord Model

@Model
final class AIAnalysisRecord {
    @Attribute(.unique) var id: UUID
    var videoID: UUID
    var eventTypeRaw: String
    var timestampSeconds: Double
    var endTimestampSeconds: Double?
    var analysisResultText: String
    /// Nil unless generated by an actual Vision / Core ML model observation. Never fabricated.
    var confidenceScore: Double?
    var modelName: String
    var modelVersion: String
    var statusRaw: String
    var metricsJSON: Data?
    var createdAt: Date

    var recording: VideoRecording?

    init(
        id: UUID = UUID(),
        videoID: UUID,
        eventType: AnalysisEventType,
        timestampSeconds: Double,
        endTimestampSeconds: Double? = nil,
        analysisResultText: String,
        confidenceScore: Double? = nil,
        modelName: String,
        modelVersion: String,
        status: AnalysisProcessingStatus,
        metrics: PoseBiomechanicsMetrics? = nil,
        createdAt: Date = Date(),
        recording: VideoRecording? = nil
    ) {
        self.id = id
        self.videoID = videoID
        self.eventTypeRaw = eventType.rawValue
        self.timestampSeconds = timestampSeconds
        self.endTimestampSeconds = endTimestampSeconds
        self.analysisResultText = analysisResultText
        self.confidenceScore = confidenceScore
        self.modelName = modelName
        self.modelVersion = modelVersion
        self.statusRaw = status.rawValue
        self.metricsJSON = metrics.flatMap { try? JSONEncoder().encode($0) }
        self.createdAt = createdAt
        self.recording = recording
    }

    var eventType: AnalysisEventType {
        get { AnalysisEventType(rawValue: eventTypeRaw) ?? .manualTechniqueNote }
        set { eventTypeRaw = newValue.rawValue }
    }

    var status: AnalysisProcessingStatus {
        get { AnalysisProcessingStatus(rawValue: statusRaw) ?? .completed }
        set { statusRaw = newValue.rawValue }
    }

    var metrics: PoseBiomechanicsMetrics? {
        get {
            guard let data = metricsJSON else { return nil }
            return try? JSONDecoder().decode(PoseBiomechanicsMetrics.self, from: data)
        }
        set {
            metricsJSON = newValue.flatMap { try? JSONEncoder().encode($0) }
        }
    }
}

